package fyi.lehlanyaverse.data

/*
 * Content model for the dossier. Layout code only ever reads these types;
 * the actual values live in Intel.kt.
 */

data class Operator(
    val name: String,
    /** Rendered as a redaction bar that declassifies on hover / focus. */
    val callsign: String,
    val role: String,
    val location: String,
    val coordinates: String,
    val status: String,
    /** Drives the availability beacon (profile + header): a pulsing "OPEN TO OPPORTUNITIES", or a dim "ON ASSIGNMENT". */
    val openToOpportunities: Boolean,
    /** Tooltip on the beacon while [openToOpportunities] is true. */
    val availabilityNote: String,
    /** Mono label above the hero brief, e.g. "Subject assessment // Operator S. Moleele". */
    val bioHeading: String,
    /** Shown in order as HUD tags under [bioHeading]. */
    val languages: List<String>,
    /** Hero brief, one entry per paragraph. `**text**` renders bold; nothing else is parsed. */
    val bio: List<String>,
    val clearance: String,
    /** Headline numbers for the profile card, e.g. Stat("4+", "Years in the field"). */
    val stats: List<Stat>,
    /** Field photos for the ID card's Polaroid stack, top first. Tapping cycles through them in order. */
    val photos: List<Photo>,
)

/**
 * A Polaroid photo. [src] is a site-relative .jpg; a .webp with the same name must sit beside it
 * (both generated by `npm --prefix tools/og run photos`). [note] is the small scrawl beside the caption.
 */
data class Photo(val src: String, val alt: String, val caption: String, val note: String? = null)

/** [redacted] hides [value] behind a black bar that declassifies on hover / tap. */
data class Stat(val value: String, val label: String, val redacted: Boolean = false)

data class Skill(
    val name: String,
    /** 0–100. Rendered as a proficiency bar with the number shown alongside. */
    val proficiency: Int,
    /** Optional one-line qualifier shown under the name, e.g. what the skill covers. */
    val note: String? = null,
)

/** Slots render in this order: primary, integration, testing, secondary, equipment, sidearms. */
data class Loadout(
    val primary: List<Skill>,
    val integration: List<Skill>,
    val testing: List<Skill>,
    val secondary: List<Skill>,
    val sidearms: List<Skill>,
    val equipment: List<Skill>,
)

data class Mission(
    val codename: String,
    val role: String,
    val unit: String,
    /** Display text, e.g. "JUL 2025". */
    val start: String,
    /** Machine-readable ISO date for <time datetime>, e.g. "2025-07". */
    val startIso: String,
    /** Null means ongoing. */
    val end: String?,
    val endIso: String?,
    val briefing: String,
    val objectives: List<String>,
    val stack: List<String>,
)

/**
 * What the paper actually is. A completion or training certificate is not an accredited certification, so it is
 * labelled as such ([corner] is the badge's short tag, [dated] the verb before the year).
 */
enum class CommendationKind(val label: String, val corner: String, val dated: String) {
    CERTIFICATION("CERTIFICATION", "CERT", "Awarded"),
    COMPLETION("COMPLETION CERTIFICATE", "COMPL", "Completed"),
    TRAINING("TRAINING CERTIFICATE", "TRAIN", "Trained"),
    EDUCATION("EDUCATION", "EDU", "Awarded"),
}

/** COMMENDATIONS is split into these, in this order. */
enum class CommendationGroup(val label: String) {
    SECURITY("Security & Compliance"),
    CLOUD("Cloud & Engineering"),
    EDUCATION("Education");

    /** Shown on the medal wall as the "Security clearance" cluster. */
    val isClearance: Boolean get() = this == SECURITY
}

data class Commendation(
    val title: String,
    /** Null shows a TODO marker until it is filled in. */
    val issuer: String?,
    val kind: CommendationKind,
    val group: CommendationGroup,
    /** Year; null shows a TODO marker until it is filled in. */
    val awarded: Int?,
    val expires: Int? = null,
    val credentialUrl: String? = null,
)

enum class AssessmentLevel(val label: String) { BASIC("Basic"), INTERMEDIATE("Intermediate"), ADVANCED("Advanced") }

/** A HackerRank certificate (with a [AssessmentLevel]) or a star-rated profile badge. */
enum class AssessmentKind(val noun: String) { CERTIFICATE("certificate"), BADGE("badge") }

/**
 * A third-party skill assessment, shown in COMMENDATIONS as "Field assessments" and as a VERIFIED marker on
 * [relatedSkill] in LOADOUT. The issuer is text only: no logos, brand colours or badge artwork.
 */
data class SkillAssessment(
    /** Skill name, e.g. "Java". */
    val name: String,
    /** Must equal a LOADOUT [Skill.name] exactly (IntelTest checks). */
    val relatedSkill: String,
    val kind: AssessmentKind = AssessmentKind.CERTIFICATE,
    /** Null (TODO): no level stamp is shown. */
    val level: AssessmentLevel? = null,
    /** [AssessmentKind.BADGE] only, 1–5. Null (TODO): no stars shown. */
    val stars: Int? = null,
    val issuer: String = "HackerRank",
    /**
     * Where to verify it. A certificate has its own public link; a badge has none, so it points at the profile
     * that shows it. Null (TODO): no VERIFY link and no LOADOUT marker, rather than a broken link.
     */
    val verifyUrl: String? = null,
) {
    val isVerifiable: Boolean get() = verifyUrl != null

    /** e.g. "HackerRank Java (Intermediate)" for a certificate, "HackerRank Java badge (3★)" for a badge. */
    val proofLabel: String
        get() = when (kind) {
            AssessmentKind.BADGE -> "$issuer $name badge" + (stars?.let { " (${it}★)" } ?: "")
            AssessmentKind.CERTIFICATE -> "$issuer $name" + (level?.let { " (${it.label})" } ?: "")
        }

    /** Accessible name for verify links; a badge is verified on the profile, so it says so. */
    val verifyLabel: String
        get() = when (kind) {
            AssessmentKind.BADGE -> "Verify $issuer $name badge on profile (opens in new tab)"
            AssessmentKind.CERTIFICATE -> "Verify $issuer $name certificate (opens in new tab)"
        }
}

enum class OpStatus(val label: String, val code: String) {
    IN_PROGRESS("IN PROGRESS", "inprogress"),
    DEPLOYED("DEPLOYED", "deployed"),
    RECON("RECON", "recon"),
}

/** Alt text is mandatory: a screenshot cannot be added without describing it. */
data class Screenshot(val src: String, val alt: String)

data class Operation(
    /** URL segment for /operations/{slug}: lowercase letters, digits and dashes. */
    val slug: String,
    val codename: String,
    val title: String,
    val status: OpStatus,
    val summary: String,
    val briefing: List<String>,
    val objectives: List<String>,
    val stack: List<String>,
    val repoUrl: String? = null,
    val liveUrl: String? = null,
    val screenshot: Screenshot? = null,
)

/** A paper's look on the evidence board (and in its pop-up). */
enum class IntelType(val label: String) {
    NOTE("Field note"),
    CLIPPING("Clipping"),
    PHOTO("Photo"),
    INDEX_CARD("Index card"),
}

/** Wording on a paper's link button. */
enum class IntelLinkLabel(val text: String) { VIEW_REPO("View repo"), READ_SOURCE("Read source") }

/** Where a paper's pin goes on the board: [x] as % of its width, [y] as % of its height. */
data class BoardSpot(val x: Double, val y: Double)

data class IntelPaper(
    /** Short slug other papers use to link to this one, e.g. "kotlin". Unique. */
    val id: String,
    val title: String,
    val type: IntelType,
    /** One line, shown on the board. */
    val teaser: String,
    /** A few sentences, shown when the paper is opened. */
    val summary: String,
    val tags: List<String>,
    /** ISO year-month, e.g. "2026-10". */
    val date: String? = null,
    val link: String? = null,
    val linkLabel: IntelLinkLabel = IntelLinkLabel.READ_SOURCE,
    /** Ids of related papers: one red string per pair, whichever side declares it. */
    val linkedTo: List<String> = emptyList(),
    /** Null: placed in a free spot automatically. */
    val position: BoardSpot? = null,
    /** Degrees. Null: a small tilt, cycled. */
    val rotation: Double? = null,
)

enum class CommsChannel { EMAIL, LINKEDIN, GITHUB, HACKERRANK }

data class CommsLink(
    val channel: CommsChannel,
    val label: String,
    val handle: String,
    val url: String,
)

/**
 * The downloadable CV. [path] is the one source file; the build copies it to the stable /cv.pdf and measures it
 * for [size]. Updating the CV is replacing that file and setting [updated] (scripts/update-cv.sh does both).
 */
data class CvFile(
    /** Source file, site-relative under public/, e.g. "/cv/Name_CV.pdf". */
    val path: String,
    /** Name the browser saves it as. */
    val fileName: String,
    /** ISO date, e.g. "2026-11-19": shown as "UPDATED NOV 2026" and used as the cache-busting ?v= on links. */
    val updated: String,
) {
    /** Stable short address, versioned so browsers and caches fetch the newest file after an update. */
    val href: String get() = "$STABLE_PATH?v=$updated"

    /** e.g. "PDF · 63 KB", measured from the real file at build time (generated CvMeta.kt). */
    val size: String get() = CV_SIZE_LABEL

    companion object {
        const val STABLE_PATH = "/cv.pdf"
    }
}
